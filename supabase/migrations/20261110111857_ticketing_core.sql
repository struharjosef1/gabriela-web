-- Authorization helpers
create or replace function public.current_user_is_ticket_assignee(target_ticket_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.ticket_assignments ta
    where ta.ticket_id = target_ticket_id
      and ta.assignee_user_id = auth.uid()
      and ta.unassigned_at is null
  );
$$;

create or replace function public.current_user_is_ticket_watcher(target_ticket_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.ticket_watchers tw
    where tw.ticket_id = target_ticket_id and tw.user_id = auth.uid()
  );
$$;

create or replace function public.current_user_can_access_ticket(target_ticket_id uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1
    from public.tickets t
    where t.id = target_ticket_id
      and (
        public.current_user_can_manage_org(t.organization_id)
        or t.reporter_user_id = auth.uid()
        or public.current_user_is_ticket_assignee(t.id)
        or public.current_user_is_ticket_watcher(t.id)
        or public.current_user_has_active_support_grant(t.organization_id)
      )
  );
$$;

